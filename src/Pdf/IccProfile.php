<?php

declare(strict_types=1);

namespace IvoPdf\Pdf;

/**
 * Generates a minimal ICC v2 sRGB (IEC 61966-2.1 primaries, D50-adapted) display profile in pure PHP,
 * suitable as the PDF/A OutputIntent destination profile.
 */
final class IccProfile
{
    public static function srgb(): string
    {
        $tags = [];
        $tags['cprt'] = self::textTag('Public Domain. Generated by IvoPDF.');
        $tags['desc'] = self::descTag('sRGB IEC61966-2.1');
        $tags['wtpt'] = self::xyzTag(0.9642, 1.0, 0.8249);
        $tags['rXYZ'] = self::xyzTag(0.4360747, 0.2225045, 0.0139322);
        $tags['gXYZ'] = self::xyzTag(0.3850649, 0.7168786, 0.0971045);
        $tags['bXYZ'] = self::xyzTag(0.1430804, 0.0606169, 0.7141733);
        $curve = self::curveTag();
        $tags['rTRC'] = $curve;

        ksort($tags);
        $names = array_keys($tags);
        $tagCount = count($names) + 2; // gTRC and bTRC share the rTRC data
        $offset = 128 + 4 + 12 * $tagCount;
        $table = pack('N', $tagCount);
        $data = '';
        $positions = [];
        foreach ($names as $name) {
            $positions[$name] = [$offset + strlen($data), strlen($tags[$name])];
            $data .= $tags[$name] . str_repeat("\0", (4 - strlen($tags[$name]) % 4) % 4);
        }
        $entries = [];
        foreach ($names as $name) {
            $entries[$name] = $positions[$name];
        }
        $entries['gTRC'] = $positions['rTRC'];
        $entries['bTRC'] = $positions['rTRC'];
        ksort($entries);
        foreach ($entries as $name => [$off, $size]) {
            $table .= $name . pack('NN', $off, $size);
        }

        $size = 128 + strlen($table) + strlen($data);
        $header = pack('N', $size)
            . "\0\0\0\0"                       // preferred CMM
            . "\x02\x10\x00\x00"               // version 2.1.0
            . 'mntr' . 'RGB ' . 'XYZ '
            . pack('nnnnnn', 2024, 1, 1, 0, 0, 0)
            . 'acsp'
            . 'MSFT'                           // primary platform
            . "\0\0\0\0"                       // flags
            . "\0\0\0\0" . "\0\0\0\0"          // manufacturer, model
            . str_repeat("\0", 8)              // attributes
            . pack('N', 0)                     // rendering intent: perceptual
            . self::s15(0.9642) . self::s15(1.0) . self::s15(0.8249) // PCS illuminant D50
            . "\0\0\0\0"                       // creator
            . str_repeat("\0", 16)             // profile ID
            . str_repeat("\0", 28);            // reserved
        return $header . $table . $data;
    }

    private static function s15(float $v): string
    {
        return pack('N', (int) round($v * 65536) & 0xFFFFFFFF);
    }

    private static function xyzTag(float $x, float $y, float $z): string
    {
        return 'XYZ ' . "\0\0\0\0" . self::s15($x) . self::s15($y) . self::s15($z);
    }

    private static function textTag(string $text): string
    {
        return 'text' . "\0\0\0\0" . $text . "\0";
    }

    private static function descTag(string $text): string
    {
        return 'desc' . "\0\0\0\0" . pack('N', strlen($text) + 1) . $text . "\0"
            . pack('NN', 0, 0)                  // Unicode language code + count
            . pack('nC', 0, 0) . str_repeat("\0", 67); // ScriptCode code + count + 67 bytes
    }

    /** sRGB transfer curve sampled to a 1024 entry 'curv' table. */
    private static function curveTag(): string
    {
        $n = 1024;
        $out = 'curv' . "\0\0\0\0" . pack('N', $n);
        for ($i = 0; $i < $n; $i++) {
            $c = $i / ($n - 1);
            $lin = $c <= 0.04045 ? $c / 12.92 : (($c + 0.055) / 1.055) ** 2.4;
            $out .= pack('n', (int) round(min(1.0, max(0.0, $lin)) * 65535));
        }
        return $out;
    }
}
